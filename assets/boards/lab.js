function val(fields, id){ return String((fields && fields[id]) || "").trim(); }

function buildReport(fields){
  var out = ["Звіт з лабораторної роботи"];
  REPORT_FIELDS.forEach(function(f){
    var v = val(fields, f.id);
    if (v) out.push(f.label + ":\n" + v);
  });
  return out.join("\n\n");
}

function gradeReport(fields){
  var missing = [], hints = [];
  REPORT_FIELDS.forEach(function(f){
    var v = val(fields, f.id);
    if (f.required && !v) missing.push(f.label);
    else if (v && v.length < 15) hints.push("Розгорни поле «" + f.label + "»: одне-два слова замало.");
  });
  if (!val(fields, "code")) hints.push("Додай ключові рядки коду: за ними видно, що саме ти змінював чи змінювала.");
  if (!val(fields, "problems")) hints.push("Опиши, що пішло не так, навіть якщо дрібниця: так вчаться знаходити причини.");
  if (!missing.length && !hints.length) hints.push("Звіт повний. Покажи його вчителю.");
  return { missing: missing, hints: hints };
}

